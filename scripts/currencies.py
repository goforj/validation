#!/usr/bin/env python3
"""Generate typed currency identifiers and fluent selectors from the pinned code list."""

from pathlib import Path
import re
import subprocess


def read_codes(source):
    """Reject ambiguous or malformed input before emitting exported Go identifiers."""
    codes = [line.strip() for line in source.splitlines() if line.strip() and not line.lstrip().startswith("#")]
    if not codes or any(re.fullmatch(r"[A-Z]{3}", code) is None for code in codes):
        raise ValueError("currency codes must be nonempty ASCII uppercase three-letter identifiers")
    if len(codes) != len(set(codes)):
        raise ValueError("duplicate currency identifier")
    return sorted(codes)


def render(codes):
    """Keep constants and their selector methods in one deterministic projection."""
    source = '// Code generated by scripts/currencies.py; DO NOT EDIT.\n\npackage validation\n\nconst (\n'
    for code in codes:
        source += f'// {code} identifies the ISO 4217 {code} code without prescribing monetary behavior.\n{code} CurrencyCode = "{code}"\n'
    source += ')\n\n'
    for code in codes:
        source += f"// {code} adds {code} to the field's shared currency allowlist.\nfunc (b CurrencyField[T]) {code}() CurrencyField[T] {{ return b.allow({code}) }}\n\n"
    return source


def generate(root):
    """Format and write only a validated projection of the checked-in snapshot."""
    codes = read_codes((root / 'testdata/currency-codes.txt').read_text())
    source = subprocess.check_output(['gofmt'], input=render(codes), text=True)
    (root / 'currency_codes.go').write_text(source)


if __name__ == '__main__':
    generate(Path(__file__).resolve().parent.parent)
